#!/usr/bin/env python3
"""Generate the daily puzzles, and the pgTAP tests for the daily scorers.

Puzzles are rows of public.daily_puzzles, and they live only in the migrations
this script writes (shared/supabase/migrations/*_add_daily_puzzles.sql). A run
appends the days after each game's last puzzle, through --through, as one new
migration. It never changes a puzzle: a migration on master may already be
deployed and played, CI refuses edits to it, and a second row for a day fails
the deploy. The first day in daily_puzzles is the cutover from the old daily.

Each game is a plugin, scripts/daily_puzzles/<game>.py, which defines:

  GAME = "hot_or_cold"                           a public.daily_game value
  def pick(draw: Draw) -> dict | None            the payload for draw.day, or None
                                                 when no answer is free
  def answers(payload: dict) -> set[str]         the ISO codes it gives away
  def validate(payload: dict, world: World) -> list[str]
                                                 what is wrong with it, if anything

Every puzzle is checked, old and new: its answers are countries in
world.geojson, the plugin finds nothing wrong, each game has a puzzle every day
from its first, and no answer comes back within NO_REPEAT_DAYS days in the same
game. Different games may share an answer.

The scorers are pinned by shared vectors, shared/fixtures/daily/<game>.json,
which the iOS and Android tests read too:

  {"cases": [{"name": "...", "puzzle": {...}, "guesses": ["FR"],
              "hints_used": 0, "graph_version": null,
              "server": {"score": 1, "solved": true}}]}

`hints_used` and `graph_version` are optional, and a case without `server` is
for the apps only. `server` is {"score", "solved"}, or {"error": "<message>"}
for a submission the server refuses. Each file becomes
shared/supabase/tests/daily_<game>_vectors_test.sql, which runs the cases
through public.score_daily.

Usage:  python3 scripts/generate_daily_puzzles.py [--through YYYY-MM-DD] [--start YYYY-MM-DD] [--check]

  --through  generate every game's puzzles up to and including this day
  --start    the first day of a game that has no puzzles yet (default: tomorrow, UTC)
  --check    exit non-zero if a puzzle is invalid or a generated file is stale (for CI)
"""

from __future__ import annotations

import argparse
import datetime as dt
import importlib.util
import json
import random
import re
import sys
from dataclasses import dataclass
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
WORLD = REPO_ROOT / "shared/data/world.geojson"
PLUGINS = REPO_ROOT / "scripts/daily_puzzles"
MIGRATIONS = REPO_ROOT / "shared/supabase/migrations"
MIGRATION_SUFFIX = "_add_daily_puzzles.sql"
FIXTURES = REPO_ROOT / "shared/fixtures/daily"
TESTS = REPO_ROOT / "shared/supabase/tests"

GAMES = ("shortest_route", "trivia", "hot_or_cold")
NO_REPEAT_DAYS = 60

HEADER = [
    "-- Generated by scripts/generate_daily_puzzles.py. Do not edit: once on master, these",
    "-- puzzles may be live. Generate more with a new run instead.",
    "",
    "insert into public.daily_puzzles (date, game, payload) values",
]
ROW = re.compile(r"^  \('(\d{4}-\d{2}-\d{2})', '([a-z_]+)', '(.*)'\)([,;])$")


# ---------------------------------------------------------------------------
# What plugins get


@dataclass(frozen=True)
class Country:
    iso: str
    name: str
    continent: str
    capitals: tuple[str, ...]
    is_point: bool


class World:
    """The countries in world.geojson."""

    def __init__(self) -> None:
        with WORLD.open() as handle:
            features = json.load(handle)["features"]
        self.countries: dict[str, Country] = {}
        for feature in features:
            iso, props = feature.get("id"), feature["properties"]
            if not iso:
                continue
            capitals = [props["capital"]] if props.get("capital") else []
            capitals += [c["name"] for c in props.get("otherCapitals", [])]
            self.countries[iso] = Country(
                iso=iso,
                name=props["name"],
                continent=props["continent"],
                capitals=tuple(capitals),
                is_point=(feature.get("geometry") or {}).get("type") == "Point",
            )


@dataclass
class Draw:
    """One day's pick: `blocked` holds this game's answers from the last NO_REPEAT_DAYS
    days, and `used` all its puzzles so far, oldest first."""

    day: dt.date
    world: World
    rng: random.Random
    blocked: frozenset[str]
    used: list[dict]


@dataclass(frozen=True)
class Puzzle:
    day: dt.date
    game: str
    payload: dict


# ---------------------------------------------------------------------------
# Plugins and puzzles


def load_plugins() -> dict:
    plugins = {}
    for path in sorted(PLUGINS.glob("*.py")) if PLUGINS.is_dir() else []:
        if path.name.startswith("_"):
            continue
        spec = importlib.util.spec_from_file_location(f"daily_puzzles.{path.stem}", path)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        if module.GAME not in GAMES or module.GAME != path.stem:
            raise SystemExit(f"{path.relative_to(REPO_ROOT)}: GAME must be its file name and one of {GAMES}")
        plugins[module.GAME] = module
    return plugins


def read_migrations() -> dict[Path, list[Puzzle]]:
    found = {}
    for path in sorted(MIGRATIONS.glob(f"*{MIGRATION_SUFFIX}")):
        lines = path.read_text().splitlines()
        if lines[: len(HEADER)] != HEADER:
            raise SystemExit(f"{path.relative_to(REPO_ROOT)}: not written by this script")
        puzzles = []
        for number, line in enumerate(lines[len(HEADER):], len(HEADER) + 1):
            match = ROW.match(line)
            if not match:
                raise SystemExit(f"{path.relative_to(REPO_ROOT)}:{number}: unexpected line")
            day, game, payload, _ = match.groups()
            puzzles.append(Puzzle(dt.date.fromisoformat(day), game, json.loads(payload.replace("''", "'"))))
        found[path] = puzzles
    return found


def payload_json(payload: dict) -> str:
    return json.dumps(payload, ensure_ascii=False, sort_keys=True, separators=(", ", ": "))


def sql_text(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def render_migration(puzzles: list[Puzzle]) -> str:
    rows = [
        f"  ('{p.day.isoformat()}', '{p.game}', {sql_text(payload_json(p.payload))})"
        for p in sorted(puzzles, key=lambda p: (p.day, p.game))
    ]
    return "\n".join(HEADER) + "\n" + ",\n".join(rows) + ";\n"


def problems(puzzles: list[Puzzle], plugins: dict, world: World) -> list[str]:
    found = []
    by_game: dict[str, list[dt.date]] = {}
    by_answer: dict[tuple[str, str], list[dt.date]] = {}
    for puzzle in sorted(puzzles, key=lambda p: (p.day, p.game)):
        where = f"{puzzle.day} {puzzle.game}"
        plugin = plugins.get(puzzle.game)
        if plugin is None:
            found.append(f"{where}: no plugin for {puzzle.game}")
            continue
        by_game.setdefault(puzzle.game, []).append(puzzle.day)
        found += [f"{where}: {problem}" for problem in plugin.validate(puzzle.payload, world)]
        for code in sorted(plugin.answers(puzzle.payload)):
            if code not in world.countries:
                found.append(f"{where}: {code} is not a country in world.geojson")
            by_answer.setdefault((puzzle.game, code), []).append(puzzle.day)

    for game, days in by_game.items():
        for earlier, later in zip(days, days[1:]):
            if later == earlier:
                found.append(f"{later} {game}: two puzzles")
            elif later != earlier + dt.timedelta(days=1):
                found.append(f"{game}: no puzzles from {earlier + dt.timedelta(days=1)} to {later - dt.timedelta(days=1)}")

    for (game, code), days in by_answer.items():
        for earlier, later in zip(days, days[1:]):
            if (later - earlier).days < NO_REPEAT_DAYS:
                found.append(f"{game}: {code} is the answer on {earlier} and again on {later}")
    return found


def generate(existing: list[Puzzle], plugins: dict, world: World, start: dt.date, through: dt.date) -> list[Puzzle]:
    puzzles = list(existing)
    first_day = {
        game: max((p.day for p in existing if p.game == game), default=start - dt.timedelta(days=1))
        + dt.timedelta(days=1)
        for game in plugins
    }
    new = []
    day = min(first_day.values(), default=through + dt.timedelta(days=1))
    while day <= through:
        for game in sorted(g for g in plugins if first_day[g] <= day):
            plugin = plugins[game]
            used = [p for p in puzzles if p.game == game]
            blocked = frozenset(
                code
                for p in used
                if (day - p.day).days < NO_REPEAT_DAYS
                for code in plugin.answers(p.payload)
            )
            draw = Draw(day, world, random.Random(f"{game}:{day.isoformat()}"), blocked, [p.payload for p in used])
            payload = plugin.pick(draw)
            if payload is None:
                raise SystemExit(f"{game} has no free answer on {day}")
            puzzle = Puzzle(day, game, payload)
            puzzles.append(puzzle)
            new.append(puzzle)
        day += dt.timedelta(days=1)
    return new


# ---------------------------------------------------------------------------
# Scorer vectors as pgTAP


def render_vectors_test(game: str, cases: list[dict]) -> str:
    tests = []
    for case in cases:
        if "server" not in case:
            continue
        call = (
            f"public.score_daily('{game}', {sql_text(payload_json(case['puzzle']))}, "
            f"{sql_text(json.dumps(case['guesses']))}, {int(case.get('hints_used', 0))}, "
            f"{'null' if case.get('graph_version') is None else sql_text(case['graph_version'])})"
        )
        server, name = case["server"], sql_text(case["name"])
        if "error" in server:
            tests.append(f"select throws_ok({sql_text('select ' + call)}, '22023', {sql_text(server['error'])}, {name});")
        else:
            expected = f"row({int(server['score'])}, {'true' if server['solved'] else 'false'})::public.daily_score"
            tests.append(f"select is({call}, {expected}, {name});")
    return (
        f"-- Generated by scripts/generate_daily_puzzles.py from shared/fixtures/daily/{game}.json,\n"
        "-- the vectors the iOS and Android tests read too. Do not edit: regenerate.\n"
        "begin;\n"
        f"select plan({len(tests)});\n\n"
        + "\n".join(tests)
        + "\n\nselect * from finish();\nrollback;\n"
    )


def vectors_tests() -> tuple[dict[Path, str], list[Path]]:
    """The pgTAP test each game's vectors make, and stale ones whose vectors are gone."""
    outputs = {}
    for game in GAMES:
        fixture = FIXTURES / f"{game}.json"
        if fixture.exists():
            with fixture.open() as handle:
                outputs[TESTS / f"daily_{game}_vectors_test.sql"] = render_vectors_test(game, json.load(handle)["cases"])
    orphans = [p for p in TESTS.glob("daily_*_vectors_test.sql") if p not in outputs]
    return outputs, orphans


# ---------------------------------------------------------------------------


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--through", type=dt.date.fromisoformat, help="generate puzzles up to this day")
    parser.add_argument("--start", type=dt.date.fromisoformat, help="first day of a game with no puzzles yet")
    parser.add_argument("--check", action="store_true", help="verify the puzzles and generated files instead")
    args = parser.parse_args()
    if args.check == bool(args.through):
        parser.error("pass either --through or --check")

    plugins = load_plugins()
    world = World()
    migrations = read_migrations()
    existing = [p for puzzles in migrations.values() for p in puzzles]
    tests, orphans = vectors_tests()

    if args.check:
        stale = [p for p, puzzles in migrations.items() if p.read_text() != render_migration(puzzles)]
        stale += [p for p, content in tests.items() if not p.exists() or p.read_text() != content]
        found = problems(existing, plugins, world)
        for problem in found:
            print(problem, file=sys.stderr)
        for path in stale:
            print(f"{path.relative_to(REPO_ROOT)} is stale — run scripts/generate_daily_puzzles.py", file=sys.stderr)
        for path in orphans:
            print(f"{path.relative_to(REPO_ROOT)} has no vectors — delete it", file=sys.stderr)
        if found or stale or orphans:
            return 1
        print(f"{len(existing)} daily puzzles are valid and the generated files are up to date")
        return 0

    tomorrow = dt.datetime.now(dt.timezone.utc).date() + dt.timedelta(days=1)
    start = args.start or tomorrow
    if start < tomorrow:
        parser.error(f"--start must be {tomorrow} (tomorrow, UTC) or later")
    new = generate(existing, plugins, world, start, args.through)
    found = problems(existing + new, plugins, world)
    if found:
        print("\n".join(found), file=sys.stderr)
        return 1

    for path, content in tests.items():
        path.write_text(content)
        print(f"wrote {path.relative_to(REPO_ROOT)}")
    for path in orphans:
        path.unlink()
        print(f"deleted {path.relative_to(REPO_ROOT)}")
    if not new:
        print(f"no new puzzles: every game already runs through {args.through}" if plugins else "no game plugins yet")
        return 0
    stamp = dt.datetime.now(dt.timezone.utc).strftime("%Y%m%d%H%M%S")
    path = MIGRATIONS / f"{stamp}{MIGRATION_SUFFIX}"
    path.write_text(render_migration(new))
    days = sorted({p.day for p in new})
    print(f"wrote {path.relative_to(REPO_ROOT)}: {len(new)} puzzles, {days[0]} to {days[-1]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
